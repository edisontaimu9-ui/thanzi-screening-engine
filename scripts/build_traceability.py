"""Rule traceability: every CMAM rule, its source and page, and the tests that make it fire (Phase 7, D94).

    python scripts/build_traceability.py                       # run the suite, write docs/testing/traceability.md
    python scripts/build_traceability.py --check               # run the suite, fail if any rule has no test
    python scripts/build_traceability.py --check --trace-file T # reuse a trace JSON from a run that used the plugin

A rule counts as tested when a test makes it appear in `rules_fired`. That shows the rule was exercised, not that
its threshold is clinically right: Maria's review covers that.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
OUT = ROOT / "docs" / "testing" / "traceability.md"


def run_suite() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        trace = Path(tmp) / "trace.json"
        env = {**os.environ, "THANZI_TRACE_OUT": str(trace)}
        proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "tests._trace_plugin"], cwd=ROOT, env=env)
        if not trace.exists():
            raise SystemExit("trace file was not written; did the plugin load?")
        data = json.loads(trace.read_text(encoding="utf-8"))
        data["pytest_returncode"] = proc.returncode
        return data


ORDER = ("tests/rules/", "tests/safety/", "tests/properties/", "tests/explain/", "tests/ml/", "tests/anthro/", "tests/data/", "tests/api/")


def _prefer_rule_tests(tests: list[str]) -> list[str]:
    return sorted(tests, key=lambda t: (next((i for i, d in enumerate(ORDER) if t.startswith(d)), len(ORDER)), t))


def render(fired: dict[str, list[str]]) -> str:
    from thanzi_screen.rules.rules_v2016 import RULES, RULE_SET_VERSION
    lines = [
        "# Rule traceability",
        "",
        f"Rule set `{RULE_SET_VERSION}`. Generated by `scripts/build_traceability.py` from a full test run. "
        "A rule counts as tested when at least one test makes it appear in `rules_fired`. "
        "This shows the rule is exercised, not that its threshold is clinically right (Maria's review covers that).",
        "",
        "| Rule | Rule text | Source, page | Tag | Tests | Example tests |",
        "|---|---|---|---|---|---|",
    ]
    missing = []
    for rid, rule in RULES.items():
        tests = _prefer_rule_tests(fired.get(rid, []))
        if not tests:
            missing.append(rid)
        examples = "<br>".join(f"`{t}`" for t in tests[:3]) or "**none**"
        lines.append(f"| `{rid}` | {rule.description} | {rule.source} {rule.page} | {rule.tag} | {len(tests)} | {examples} |")
    lines += ["", f"Rules in the registry: {len(RULES)}. Rules with no test: " + (", ".join(f"`{m}`" for m in missing) if missing else "none") + ".", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any rule has no test or the committed file lists different rules")
    ap.add_argument("--trace-file", help="reuse a trace JSON written by tests._trace_plugin instead of running the suite")
    args = ap.parse_args()

    from thanzi_screen.rules.rules_v2016 import RULES
    if args.trace_file:
        data = json.loads(Path(args.trace_file).read_text(encoding="utf-8"))
        data["pytest_returncode"] = data.get("exitstatus", 0)
    else:
        data = run_suite()
    if data["pytest_returncode"] != 0:
        print("test suite failed; no traceability output", file=sys.stderr)
        return 1
    fired = data["fired"]
    unknown = sorted(set(fired) - set(RULES))
    missing = sorted(r for r in RULES if not fired.get(r))
    if unknown:
        print("rules fired that are not in the registry:", ", ".join(unknown), file=sys.stderr)
        return 1
    if args.check:
        if missing:
            print("rules with no test: " + ", ".join(missing), file=sys.stderr)
            return 1
        committed = set(re.findall(r"^\| `([A-Z0-9_.]+)` \|", OUT.read_text(encoding="utf-8") if OUT.exists() else "", re.M))
        if committed != set(RULES):
            print("docs/testing/traceability.md lists different rules. Run: python scripts/build_traceability.py", file=sys.stderr)
            return 1
        print(f"all {len(RULES)} rules have at least one test; docs/testing/traceability.md lists them.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(fired), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}; rules with no test: {', '.join(missing) or 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
