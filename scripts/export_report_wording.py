"""Write or check the wording review sheet for clinicians: docs/review/child-report-wording.md (Phase 9).

    python scripts/export_report_wording.py            # regenerate the sheet
    python scripts/export_report_wording.py --check    # exit 1 if the committed sheet is stale (CI)

The sheet lists every sentence the child report adds of its own (src/thanzi_screen/childreport/wording.py) and the Phase 8
consolidated prediction wording and severity order, so reviewers read and sign off both in one sitting. It needs no extra packages.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
OUT = ROOT / "docs" / "review" / "child-report-wording.md"

# Phase 8 wording that lives inline in prediction/consolidate.py. tests/childreport/test_wording.py checks each of these is still there.
PHASE8_PHRASES = (
    ("high stratum clause", "one of the highest chances of"),
    ("elevated stratum clause", "a higher than usual chance of"),
    ("opening", "The prediction models estimate"),
    ("closing", "Consider closer follow-up and a clinician review."),
)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    from thanzi_screen.childreport import wording as W
    from thanzi_screen.explain.messages import CLASS_PHRASE
    from thanzi_screen.prediction.consolidate import AUTHORITY, TARGET_ORDER

    lines = [
        "# Child report wording: review sheet",
        "",
        f"Wording version `{W.WORDING_VERSION}`. Status: **{W.REVIEW_STATUS}**. Generated by `scripts/export_report_wording.py` from the code: "
        "edit the code, not this file.",
        "",
        "**What to decide.** For each line write Approve, or Change with your wording, or Reject. Check three things in every line: it never "
        "states or hints at a diagnosis, it never reassures (no \"well\", \"normal\", \"safe\"), and a missing or empty result is said to be "
        "not reassurance.",
        "",
        "## 1. Sentences the child report adds (`childreport/wording.py`)",
        "",
        "| ID | Where it appears | Text | Decision | Reviewer's wording |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| `{e.id}` | {_cell(e.used_in)} | {_cell(e.text)} | | |" for e in W.all_entries()]
    lines += [
        "",
        "## 2. Phase 8: consolidated prediction wording (`prediction/consolidate.py`)",
        "",
        "These are drafts. The sentence is built as: *opening* + clauses (the *high* clause first, then the *elevated* clause, joined by \"; and\") "
        "+ \"between X and Y months from now.\" + *closing*.",
        "",
        "| Part | Text | Decision | Reviewer's wording |",
        "|---|---|---|---|",
    ]
    lines += [f"| {part} | {_cell(text)} | | |" for part, text in PHASE8_PHRASES]
    lines += [
        f"| authority statement | {_cell(AUTHORITY)} | | |",
        "",
        "**Severity order** of the concerns, most severe first: "
        + ", ".join(f"`{t}`" for t in TARGET_ORDER)
        + ". Within one order, the *high* stratum comes before *elevated*. Decision: ______",
        "",
        "## 3. Copied into the report unchanged (for reference)",
        "",
        "The report quotes these from the screening result, so reviewers see them in the report even though another module owns them.",
        "",
        "| Classification | Text |",
        "|---|---|",
    ]
    lines += [f"| `{k}` | {_cell(v)} |" for k, v in CLASS_PHRASE.items()]
    lines += [
        "",
        "Not listed: rule reasons, growth messages, recording-error and review messages. They are in `explain/messages.py` and `growth/`.",
        "",
        "## Sign-off",
        "",
        "Reviewer name and role: ______  Date: ______  Outcome (approved, approved with changes, not approved): ______",
        "",
        "Until this is signed, `/v1/report` stays off (`THANZI_CHILD_REPORT_ENABLED` is not `1`). The sign-off file and the deployment "
        "gate that checks it are Phase 11.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed sheet differs from the code")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/review/child-report-wording.md is stale. Run: python scripts/export_report_wording.py", file=sys.stderr)
            return 1
        print("docs/review/child-report-wording.md is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
